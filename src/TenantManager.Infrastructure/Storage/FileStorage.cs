using System.Text.RegularExpressions;
using Azure;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;
using Microsoft.Extensions.Options;
using TenantManager.Application.Abstractions;

namespace TenantManager.Infrastructure.Storage;

public sealed class StorageOptions
{
    public const string Section = "Storage";

    /// <summary>"Local" (a folder on disk) or "AzureBlob" (Azure Storage or the Azurite emulator).</summary>
    public string Provider { get; set; } = "Local";

    public string LocalPath { get; set; } = "data/files";

    public string? AzureConnectionString { get; set; }

    public string Container { get; set; } = "documents";
}

internal static partial class StorageKeys
{
    /// <summary>Keys are generated by the app (e.g. leases/{id}/{id}.pdf); anything else is refused.</summary>
    public static string Check(string key)
    {
        if (!Pattern().IsMatch(key) || key.Contains("..", StringComparison.Ordinal))
            throw new ArgumentException($"Invalid storage key '{key}'.", nameof(key));
        return key;
    }

    [GeneratedRegex(@"^[a-z0-9][a-z0-9/_\-\.]{0,199}$")]
    private static partial Regex Pattern();
}

/// <summary>Stores files in a folder. For local development and tests.</summary>
public sealed class LocalFileStorage : IFileStorage
{
    private readonly string _root;

    public LocalFileStorage(IOptions<StorageOptions> options)
    {
        _root = Path.GetFullPath(options.Value.LocalPath);
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken cancellationToken)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, true);
        await content.CopyToAsync(file, cancellationToken);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        var path = Resolve(key);
        Stream? stream = File.Exists(path)
            ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, true)
            : null;
        return Task.FromResult(stream);
    }

    private string Resolve(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_root, StorageKeys.Check(key)));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new ArgumentException($"Invalid storage key '{key}'.", nameof(key));
        return path;
    }
}

/// <summary>Stores files as private blobs in Azure Storage (or Azurite locally). ADR-0005.</summary>
public sealed class AzureBlobFileStorage(IOptions<StorageOptions> options) : IFileStorage
{
    private readonly BlobContainerClient _container = new(
        options.Value.AzureConnectionString
        ?? throw new InvalidOperationException("Storage:AzureConnectionString is not configured."),
        options.Value.Container);

    private readonly SemaphoreSlim _createLock = new(1, 1);
    private bool _containerReady;

    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken cancellationToken)
    {
        await EnsureContainerAsync(cancellationToken);
        await _container.GetBlobClient(StorageKeys.Check(key)).UploadAsync(content, new BlobUploadOptions
        {
            HttpHeaders = new BlobHttpHeaders { ContentType = contentType },
            Conditions = new BlobRequestConditions { IfNoneMatch = ETag.All }, // never overwrite
        }, cancellationToken);
    }

    public async Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        try
        {
            return await _container.GetBlobClient(StorageKeys.Check(key))
                .OpenReadAsync(cancellationToken: cancellationToken);
        }
        catch (RequestFailedException ex) when (ex.Status == 404)
        {
            return null;
        }
    }

    private async Task EnsureContainerAsync(CancellationToken cancellationToken)
    {
        if (_containerReady) return;
        await _createLock.WaitAsync(cancellationToken);
        try
        {
            if (!_containerReady)
            {
                await _container.CreateIfNotExistsAsync(PublicAccessType.None, null, null, cancellationToken);
                _containerReady = true;
            }
        }
        finally
        {
            _createLock.Release();
        }
    }
}
